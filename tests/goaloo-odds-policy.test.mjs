import assert from 'node:assert/strict';
const {goalooLiveOdds,goalooOddsAvailability,inQuotedOddsRange,valuePickCounts}=await import('../src/lib/goaloo-odds-policy.ts');
const quote=(market,bookmaker,odds)=>({market,bookmaker,odds});
const oneBook=['home','draw','away'].map(market=>quote(market,'Book A',2));
assert.equal(goalooOddsAvailability(goalooLiveOdds(oneBook)),'insufficient_bookmakers');
assert.equal(goalooOddsAvailability(goalooLiveOdds([...oneBook,...oneBook])),'insufficient_bookmakers','Repeated rows must not invent bookmaker agreement');
const twoBooks=[...oneBook,...oneBook.map(q=>({...q,bookmaker:'Book B',odds:3}))];
const winnerOnly=goalooLiveOdds(twoBooks);
assert.equal(winnerOnly.matchWinner.oH,2.5);
assert.equal(goalooOddsAvailability(winnerOnly),'available');
assert.equal(goalooOddsAvailability(winnerOnly,'over_2_5_goals'),'missing_market');
const totalOnly=goalooLiveOdds(['A','B'].flatMap(book=>[quote('total-over-2.5',book,1.8),quote('total-under-2.5',book,2)]));
assert.equal(goalooOddsAvailability(totalOnly),'available');
assert.equal(goalooOddsAvailability(totalOnly,'match_winner'),'missing_market');
assert.equal(goalooOddsAvailability(goalooLiveOdds([quote('total-over-3', 'A', 2)])),'missing_market');
assert(inQuotedOddsRange({market_odds:1.8,confidence:80},1.5,2.3));
assert(!inQuotedOddsRange({market_odds:1.2,confidence:60},1.5,2.3));
for(const odds of [null,undefined,NaN,Infinity,1])assert(!inQuotedOddsRange({market_odds:odds},1,3));
assert.deepEqual(valuePickCounts([{match_id:'a',expected_value:.1},{match_id:'a',expected_value:.2},{match_id:'b',expected_value:-.1},{match_id:'c',expected_value:.5},{match_id:'d',expected_value:null}]),{positiveEvPicks:3,dailyEligibleMatches:1});
console.log('Odds coverage uses distinct bookmakers, exact markets, actual quoted prices and separate positive-EV counts.');
